#!/usr/bin/env python3
"""Pinned Unicode simple-fold equivalence and Uppercase property, without host UCD."""
from pathlib import Path
import ast,hashlib,json,re,sys
r=Path(__file__).resolve().parents[1];v=r/'unicode/regex-syntax-0.8.6'
m=json.loads((v/'provenance.json').read_text())
def read(name):
 b=(v/name).read_bytes();assert hashlib.sha256(b).hexdigest()==m['files'][name];return b.decode()
def literal(s):return ast.literal_eval(re.sub(r'\\u\{([0-9a-fA-F]+)\}',lambda m:'\\U%08x'%int(m[1],16),s))
fold=[]
for line in read('case_folding_simple.rs').splitlines():
 if line.strip().startswith("('"):
  cp,others=literal(line.strip().rstrip(',').replace('&[','['));fold.append((ord(cp),list(map(ord,others))))
assert fold and all(fold[i-1][0]<fold[i][0] for i in range(1,len(fold)))
d=dict(fold)
for cp,others in fold:
 assert 1<=len(others)<=3 and cp not in others
 assert all(set(d[x]+[x])==set(others+[cp]) for x in others)
upper=read('property_bool.rs').split('pub const UPPERCASE:',1)[1].split('];',1)[0]
pairs=[tuple(map(ord,literal(line.strip().rstrip(',')))) for line in upper.splitlines() if line.strip().startswith("('")]
assert pairs and all(pairs[i-1][1]<pairs[i][0] for i in range(1,len(pairs)))
out=['''/* Generated by tools/generate-search-case.py; Unicode 16.0.0.
 * Pinned regex-syntax 0.8.6; licenses/provenance in unicode/regex-syntax-0.8.6/.
 */
#ifndef CONSOLENG_SEARCH_CASE_H
#define CONSOLENG_SEARCH_CASE_H
struct con_case_entry { ULONG cp, canonical, other[3]; UBYTE count; };
static const struct con_case_entry con_case_table[] = {
''']
for cp,others in fold:out.append('    {0x%x,0x%x,{%s},%d},\n'%(cp,min([cp]+others),','.join('0x%x'%x for x in others+[0]*(3-len(others))),len(others)))
out.append('};\nstatic const ULONG con_uppercase[][2] = {\n')
for a,b in pairs:out.append('    {0x%x,0x%x},\n'%(a,b))
out.append('''};
static inline const struct con_case_entry *con_case_lookup(ULONG cp)
{
    ULONG lo=0,hi=sizeof(con_case_table)/sizeof(*con_case_table);
    while(lo<hi) {
        ULONG mid=lo+(hi-lo)/2;
        if(cp<con_case_table[mid].cp)hi=mid;
        else if(cp>con_case_table[mid].cp)lo=mid+1;
        else return &con_case_table[mid];
    }
    return NULL;
}
static inline ULONG con_case_fold(ULONG cp)
{
    const struct con_case_entry *entry=con_case_lookup(cp);
    return entry?entry->canonical:cp;
}
static inline BOOL con_case_upper(ULONG cp)
{
    ULONG lo=0,hi=sizeof(con_uppercase)/sizeof(*con_uppercase);
    while(lo<hi) {
        ULONG mid=lo+(hi-lo)/2;
        if(cp<con_uppercase[mid][0])hi=mid;
        else if(cp>con_uppercase[mid][1])lo=mid+1;
        else return TRUE;
    }
    return FALSE;
}
#endif
''')
p=r/'search_case.h';content=''.join(out)
if '--check' in sys.argv:assert p.read_text()==content,'Generated case tables drifted'
else:p.write_text(content)
