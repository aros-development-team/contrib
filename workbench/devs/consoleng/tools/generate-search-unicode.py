#!/usr/bin/env python3
"""Convert pinned regex-syntax Unicode 16 ranges without host Unicode dependence."""
from pathlib import Path
import hashlib,json,re,sys
root=Path(__file__).resolve().parents[1]
vendor=root/'unicode/regex-syntax-0.8.6'
meta=json.loads((vendor/'provenance.json').read_text())
def scalar(text):
 if len(text)==1:return ord(text)
 if text.startswith('\\u{') and text.endswith('}'):return int(text[3:-1],16)
 return ord({'\\t':'\t','\\n':'\n','\\r':'\r','\\0':'\0',"\\'":"'",'\\\\':'\\'}[text])
def ranges(name):
 p=vendor/name;assert hashlib.sha256(p.read_bytes()).hexdigest()==meta['files'][name],name
 pairs=[(scalar(a),scalar(b)) for a,b in re.findall(r"\('((?:\\.|[^'])*)', '((?:\\.|[^'])*)'\)",p.read_text())]
 assert pairs and all(0<=a<=b<=0x10ffff for a,b in pairs)
 assert all(pairs[i-1][1]<pairs[i][0] for i in range(1,len(pairs)))
 return pairs
out=['''/* Generated by tools/generate-search-unicode.py; do not edit.
 * Shorthand data: Unicode 16.0.0 from regex-syntax 0.8.6, pinned by Alacritty.
 * Capture-name data: Rust char Unicode 17.0.0, pinned in capture-names-rust17.json.
 * Licenses and provenance: unicode/regex-syntax-0.8.6/.
 */
#ifndef CONSOLENG_SEARCH_UNICODE_H
#define CONSOLENG_SEARCH_UNICODE_H
struct con_unicode_range { ULONG low, high; };
''']
for name,file in [('digit','perl_decimal.rs'),('space','perl_space.rs'),('word','perl_word.rs')]:
 out.append('static const struct con_unicode_range rx_unicode_'+name+'[] = {\n')
 out.extend('    {0x%x, 0x%x},\n'%pair for pair in ranges(file));out.append('};\n')
# Capture-name syntax uses Rust char properties, independently of the regex
# shorthand tables. Keep its reference compiler/Unicode version explicit.
capture=json.loads((root/'unicode/capture-names-rust17.json').read_text())
assert capture['unicode']=='17.0.0'
out.append('/* Capture-name properties: Rust char Unicode 17.0.0; see capture-names-rust17.json. */\n')
for name in ('alphabetic','numeric'):
 pairs=capture[name]
 assert pairs and all(0<=a<=b<=0x10ffff for a,b in pairs)
 assert all(pairs[i-1][1]<pairs[i][0] for i in range(1,len(pairs)))
 out.append('static const struct con_unicode_range rx_capture_'+name+'[] = {\n')
 out.extend('    {0x%x, 0x%x},\n'%tuple(pair) for pair in pairs);out.append('};\n')
out.append('''
static BOOL rx_unicode_member(const struct con_unicode_range *table, ULONG count, ULONG cp)
{
    ULONG low = 0, high = count;
    while (low < high) {
        ULONG mid = low + (high - low) / 2;
        if (cp < table[mid].low) high = mid;
        else if (cp > table[mid].high) low = mid + 1;
        else return TRUE;
    }
    return FALSE;
}
static inline BOOL rx_capture_char(ULONG cp, BOOL first)
{
    if (cp == '_') return TRUE;
    if (rx_unicode_member(rx_capture_alphabetic,
            sizeof(rx_capture_alphabetic)/sizeof(*rx_capture_alphabetic), cp)) return TRUE;
    return !first && (cp == '.' || cp == '[' || cp == ']' ||
        rx_unicode_member(rx_capture_numeric,
            sizeof(rx_capture_numeric)/sizeof(*rx_capture_numeric), cp));
}
/* Bits 0..2: digit, space, word. Bits 3..5: their complements. */
static BOOL rx_unicode_class(ULONG cp, ULONG mask)
{
    if (cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return FALSE;
    const struct con_unicode_range *tables[] = {rx_unicode_digit, rx_unicode_space, rx_unicode_word};
    const ULONG counts[] = {sizeof(rx_unicode_digit)/sizeof(*rx_unicode_digit),
        sizeof(rx_unicode_space)/sizeof(*rx_unicode_space), sizeof(rx_unicode_word)/sizeof(*rx_unicode_word)};
    for (ULONG i = 0; i < 3; i++) {
        ULONG bit = 1UL << i;
        if (!(mask & (bit | (bit << 3)))) continue;
        BOOL member = rx_unicode_member(tables[i], counts[i], cp);
        if ((member && (mask & bit)) || (!member && (mask & (bit << 3)))) return TRUE;
    }
    return FALSE;
}
#endif
''')
# General-category predicates stay in immutable tables rather than expanding
# thousands of ranges into each bounded compiled query.
def verified(name):
 p=vendor/name
 assert hashlib.sha256(p.read_bytes()).hexdigest()==meta['files'][name],name
 return p.read_text()
# Property families use separate tagged namespaces. Script_Extensions can
# differ from Script (for example Japanese shared punctuation).
script_extra=[]
for family,filename,property_name in [('sc','script.rs','Script'),('scx','script_extension.rs','Script_Extensions'),('bp','property_bool.rs',None),('age','age.rs','Age'),('gcb','grapheme_cluster_break.rs','Grapheme_Cluster_Break'),('sb','sentence_break.rs','Sentence_Break'),('wb','word_break.rs','Word_Break')]:
 text=verified(filename)
 blocks=dict(re.findall(r'pub const ([A-Z0-9_]+):[^=]+=\s*&\[(.*?)\];',text,re.S))
 if family=='bp':
  aliases=re.findall(r'\("([^"]+)", "([^"]+)"\)',verified('property_names.rs'))
 else:
  alias_text=verified('property_values.rs').split('"'+property_name+'",',1)[1].split('],',1)[0]
  aliases=re.findall(r'\("([^"]+)", "([^"]+)"\)',alias_text)
  if family in ('sc','scx'):assert {name for alias,name in aliases if name.upper() not in blocks}=={'Katakana_Or_Hiragana','Unknown'}
 aliases=[(alias,name) for alias,name in aliases if name.upper() in blocks]
 names=sorted(set(name for alias,name in aliases))
 for name in names:
  pairs=[(scalar(a),scalar(b)) for a,b in re.findall(r"\('((?:\\.|[^'])*)', '((?:\\.|[^'])*)'\)",blocks.get(name.upper(),''))]
  if family=='age':
   version=lambda value:tuple(map(int,value[1:].split('_')))
   pairs=[]
   for older in names:
    if version(older)<=version(name):
     pairs.extend((scalar(a),scalar(b)) for a,b in re.findall(r"\('((?:\\.|[^'])*)', '((?:\\.|[^'])*)'\)",blocks[older.upper()]))
   merged=[]
   for low,high in sorted(pairs):
    if merged and low<=merged[-1][1]+1:merged[-1]=(merged[-1][0],max(high,merged[-1][1]))
    else:merged.append((low,high))
   pairs=merged
  assert pairs and all(0<=a<=b<=0x10ffff for a,b in pairs),name
  assert all(pairs[i-1][1]<pairs[i][0] for i in range(1,len(pairs)))
  script_extra.append('static const struct con_unicode_range rx_'+family+'_'+name+'[] = {\n')
  script_extra.extend('    {0x%x, 0x%x},\n'%pair for pair in pairs)
  script_extra.append('};\n')
 script_extra.append('static const struct { const struct con_unicode_range *ranges; ULONG count; } rx_'+family+'_tables[] = {\n')
 for name in names:
  ident='rx_'+family+'_'+name
  script_extra.append('    {%s, sizeof(%s)/sizeof(*%s)},\n'%(ident,ident,ident))
 script_extra.append('};\nstatic const struct { const char *name; ULONG id; } rx_'+family+'_aliases[] = {\n')
 for alias,name in aliases:script_extra.append('    {"%s", %d},\n'%(alias,names.index(name)))
 script_extra.append('};\nstatic inline BOOL rx_'+family+'_member(ULONG id, ULONG cp)\n{\n    if (id >= sizeof(rx_'+family+'_tables)/sizeof(*rx_'+family+'_tables) || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return FALSE;\n    return rx_unicode_member(rx_'+family+'_tables[id].ranges, rx_'+family+'_tables[id].count, cp);\n}\n')
gc=verified('general_category.rs')
alias_text=verified('property_values.rs').split('"General_Category",',1)[1].split('],',1)[0]
aliases=re.findall(r'\("([^"]+)", "([^"]+)"\)',alias_text)
tables=dict(re.findall(r'pub const ([A-Z0-9_]+):[^=]+ =\s*&\[(.*?)\];',gc,re.S))
# Surrogates are excluded by regex-syntax because inputs are Unicode scalars.
aliases=[(alias,name) for alias,name in aliases if name!='Surrogate']
names=sorted(set(canonical for alias,canonical in aliases))
extra=script_extra
for name in names:
 pairs=[(scalar(a),scalar(b)) for a,b in re.findall(r"\('((?:\\.|[^'])*)', '((?:\\.|[^'])*)'\)",tables.get(name.upper(),''))]
 assert pairs and all(0<=a<=b<=0x10ffff for a,b in pairs),name
 assert all(pairs[i-1][1]<pairs[i][0] for i in range(1,len(pairs)))
 extra.append('static const struct con_unicode_range rx_gc_'+name+'[] = {\n')
 extra.extend('    {0x%x, 0x%x},\n'%pair for pair in pairs)
 extra.append('};\n')
extra.append('static const struct { const struct con_unicode_range *ranges; ULONG count; } rx_gc_tables[] = {\n')
for name in names:
 extra.append('    {rx_gc_%s, sizeof(rx_gc_%s)/sizeof(*rx_gc_%s)},\n'%(name,name,name))
extra.append('};\nstatic const struct { const char *name; ULONG id; } rx_gc_aliases[] = {\n')
for alias,name in aliases:extra.append('    {"%s", %d},\n'%(alias,names.index(name)))
extra.append('};\nstatic inline BOOL rx_gc_member(ULONG id, ULONG cp)\n{\n    if ((id >> 16) == 1) return rx_sc_member(id & 0xffff, cp);\n    if ((id >> 16) == 2) return rx_scx_member(id & 0xffff, cp);\n    if ((id >> 16) == 3) return rx_bp_member(id & 0xffff, cp);\n    if ((id >> 16) == 5) return rx_age_member(id & 0xffff, cp);\n    if ((id >> 16) == 6) return rx_gcb_member(id & 0xffff, cp);\n    if ((id >> 16) == 7) return rx_sb_member(id & 0xffff, cp);\n    if ((id >> 16) == 8) return rx_wb_member(id & 0xffff, cp);\n    if ((id >> 16) == 4) {\n        if (cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return FALSE;\n        if ((id & 0xffff) == 0) return TRUE;\n        if ((id & 0xffff) == 1) return cp < 128;\n        if ((id & 0xffff) == 2) return !rx_unicode_member(rx_gc_Unassigned, sizeof(rx_gc_Unassigned)/sizeof(*rx_gc_Unassigned), cp);\n        return FALSE;\n    }\n    if (id >= sizeof(rx_gc_tables)/sizeof(*rx_gc_tables) || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return FALSE;\n    return rx_unicode_member(rx_gc_tables[id].ranges, rx_gc_tables[id].count, cp);\n}\n')
out[-1]=out[-1].replace('#endif\n',''.join(extra)+'#endif\n')
content=''.join(out);target=root/'search_unicode.h'
if '--check' in sys.argv:
 assert target.read_text()==content,'Generated Unicode tables drifted'
else:target.write_text(content)
